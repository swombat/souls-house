#!/usr/bin/env node

// Regenerate after an intentional phosphor-svelte update, never from API input.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from '@phosphor-icons/core';

const root = fileURLToPath(new URL('../', import.meta.url));
const library = resolve(root, 'node_modules/phosphor-svelte');
const version = JSON.parse(readFileSync(resolve(library, 'package.json'), 'utf8')).version;
if (version !== '3.0.1') throw new Error(`Expected phosphor-svelte 3.0.1, found ${version}`);

const index = readFileSync(resolve(library, 'lib/index.js'), 'utf8');
const exports = [...index.matchAll(/export \{ default as (\w+) \} from '\.\/(\w+)\.svelte';/g)];
const names = exports
  .filter(([, name]) => name !== 'IconContext')
  .map(([, name, file]) => {
    if (name !== file || !/^[A-Z][A-Za-z0-9]*$/.test(name)) {
      throw new Error(`Unexpected icon export: ${name}`);
    }
    return name;
  })
  .sort();
if (names.length < 1500 || new Set(names).size !== names.length) {
  throw new Error('Incomplete or duplicate Phosphor exports');
}

const coreVersion = JSON.parse(
  readFileSync(resolve(root, 'node_modules/@phosphor-icons/core/package.json'), 'utf8')
).version;
if (coreVersion !== '2.1.1') throw new Error(`Expected @phosphor-icons/core 2.1.1, found ${coreVersion}`);
const metadata = new Map(icons.map((icon) => [icon.pascal_name, icon]));
const keywords = Object.fromEntries(
  names.map((name) => {
    const icon = metadata.get(name);
    if (!icon) throw new Error(`Missing Phosphor search metadata for ${name}`);
    const words = [icon.name, ...icon.categories, ...icon.tags];
    if (words.some((word) => typeof word !== 'string')) throw new Error(`Invalid keywords for ${name}`);
    return [name, [...new Set(words)].sort()];
  })
);
const categories = Object.fromEntries(names.map((name) => [name, metadata.get(name).categories]));

// Fail closed if upstream introduces anything beyond static path geometry.
function pathsFor(source, weight, name) {
  const branch = source.match(new RegExp(`weight === "${weight}"\\}(.*?)(?=\\{)`, 's'));
  if (!branch) throw new Error(`Missing ${weight} weight for ${name}`);
  const paths = [
    ...branch[1].matchAll(/<path d="([MmZzLlHhVvCcSsQqTtAa0-9., +\-]+)"(?: opacity="(0(?:\.\d+)?|1)")?\s*\/>/g),
  ];
  if (
    !paths.length ||
    branch[1].replace(/<path d="([MmZzLlHhVvCcSsQqTtAa0-9., +\-]+)"(?: opacity="(0(?:\.\d+)?|1)")?\s*\/>/g, '').trim()
  ) {
    throw new Error(`Unexpected SVG markup in ${name}/${weight}`);
  }
  return paths.map(([, d, opacity]) => `<path d="${d}"${opacity ? ` opacity="${opacity}"` : ''}/>`).join('');
}

const license = readFileSync(resolve(library, 'LICENSE'), 'utf8').trim();
const symbols = names.flatMap((name) => {
  const source = readFileSync(resolve(library, `lib/${name}.svelte`), 'utf8');
  return ['regular', 'duotone'].map(
    (weight) => `<symbol id="${name}-${weight}" viewBox="0 0 256 256">${pathsFor(source, weight, name)}</symbol>`
  );
});
const files = new Map([
  ['config/visual_tag_icons.json', `${JSON.stringify(names, null, 2)}\n`],
  ['app/frontend/assets/visual-tag-icon-keywords.json', `${JSON.stringify(keywords)}\n`],
  ['app/frontend/assets/visual-tag-icon-categories.json', `${JSON.stringify(categories)}\n`],
  [
    'app/frontend/assets/visual-tag-icons.svg',
    `<!-- Generated by scripts/generate-visual-tag-icons.mjs from phosphor-svelte ${version}.\n${license}\n-->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`,
  ],
]);

const check = process.argv.includes('--check');
for (const [path, contents] of files) {
  const target = resolve(root, path);
  if (check) {
    if (readFileSync(target, 'utf8') !== contents) throw new Error(`Stale generated catalog: ${path}`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
  }
}
console.log(
  `${check ? 'Verified' : 'Generated'} ${names.length} icons, regular and duotone (phosphor-svelte ${version})`
);
