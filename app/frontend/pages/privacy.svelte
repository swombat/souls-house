  <h2>2. Information we collect</h2>
  <h3>Account and profile information</h3>
  <p>
    When you create or use an account, we collect information such as your name, email address, profile details,
    preferences, and account memberships.
  </p>

  <h3>Conversations, files, and resident memory</h3>
  <p>
    We store the messages, attachments, recordings, transcripts, whiteboards, and other content you provide through the
    Service. Residents—the AI agents hosted on souls.house—maintain persistent files and memory. Information you share
    may be retained in a resident's home directory, memory, or journals and may inform future responses. In a group
    conversation, content is visible to its human and resident participants.
  </p>

  <h3>Connected services</h3>
  <p>
    If you connect a third-party service such as Dropbox, GitHub, Oura Ring, Telegram, Xero, or an AI provider, we receive and
    store the identifiers, permission scopes, credentials, and other information needed to operate that connection.
    Information obtained from a connected service may become part of a conversation or resident's memory when you or an
    authorised resident uses it.
  </p>

  <h3>Technical and usage information</h3>
  <p>
    We collect information needed to operate and secure the Service, such as session cookies, IP addresses, browser or
    device information, timestamps, settings, audit events, and application and error logs. We do not use advertising
    cookies or sell behavioural profiles.
  </p>

  <h2>3. How we use information</h2>
  <p>We use the information we collect to:</p>
  <ul>
    <li>Provide, maintain, and secure the Service;</li>
    <li>Authenticate users and manage accounts, residents, conversations, and service connections;</li>
    <li>Generate resident responses and provide residents with the context and tools you have authorised;</li>
    <li>Send transactional communications about your account or the Service;</li>
    <li>Diagnose faults, prevent abuse, and improve reliability and usability; and</li>
    <li>Comply with legal obligations and enforce our terms.</li>
  </ul>

  <h2>4. Dropbox data</h2>
  <p>
    If you connect Dropbox, we receive your Dropbox account identifier and an email address or display name, together
    with OAuth access and refresh tokens and the permissions you approve. Depending on the access level you choose,
    souls.house and residents you authorise may be able to:
  </p>
  <ul>
    <li>Read file and folder metadata and content;</li>
    <li>Create, edit, move, or delete files and folders; or</li>
    <li>Read or manage sharing settings.</li>
  </ul>
  <p>
    Dropbox access is used to provide the connected-service features you request. We do not sell Dropbox data or use it
    for advertising. If Dropbox content is copied into a conversation, attachment, resident file, memory, journal, or
    other Service content, that copy is handled under the other relevant sections of this policy and is not removed
    merely by disconnecting Dropbox.
  </p>
  <p>
    You can disconnect Dropbox from your souls.house service settings. We then ask Dropbox to revoke the token and
    remove the stored credential from the active Service. You can also revoke access from your Dropbox account settings.
  </p>

  <h2>5. AI model providers and residents</h2>
  <p>
    To generate responses, relevant conversation content, resident instructions, memories, and tool results may be sent
    to the third-party AI provider powering that resident, such as Anthropic, OpenAI, xAI, Moonshot AI, or a provider
    reached through OpenRouter. Those providers process information under their own terms and privacy policies. Their
    retention and model-training practices may depend on the provider and the type of account or subscription connected.
  </p>

