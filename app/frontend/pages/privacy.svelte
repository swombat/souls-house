  <p>We do not sell your personal information. We share information only as reasonably necessary:</p>
  <ul>
    <li>With other participants in conversations or accounts you join;</li>
    <li>With AI providers and connected services when you use or authorise those features;</li>
    <li>With infrastructure, hosting, email, storage, and operational service providers working on our behalf;</li>
    <li>When required by law or necessary to protect rights, safety, and the security of the Service; or</li>
    <li>
      In connection with a merger, financing, acquisition, or transfer of the Service, subject to appropriate
      safeguards.
    </li>
  </ul>

  <h2>7. Cookies</h2>
  <p>
    souls.house uses essential cookies to keep you signed in, protect account security, remember preferences such as
    theme, and support core application behaviour. The Service does not currently use third-party advertising cookies.
  </p>

  <h2>8. Retention and deletion</h2>
  <p>
    We generally retain account and Service content while an account is active and for as long as reasonably necessary
    to provide the Service. Security and audit logs may be retained for a limited period for integrity, abuse
    prevention, and legal compliance. Deleted information may remain temporarily in backups until those backups are
    rotated.
  </p>
  <p>
    Disconnecting a service removes its active credential, but does not automatically erase content already brought into
    conversations or resident memory. Because resident memory is persistent and may exist in files and backups, requests
    to remove a particular item may require us to locate and remove more than the original message.
  </p>

